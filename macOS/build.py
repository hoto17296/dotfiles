"""defaults.jsonc を読み込み、defaults コマンドを列挙したシェルスクリプトを出力する

使い方: python3 build.py < defaults.jsonc > defaults.sh

※ macOS 標準の python3 (3.9) で動くよう、標準モジュールのみを使用する
"""

import json
import re
import shlex
import sys
from xml.sax.saxutils import escape

WRAPPER_FIELDS = {"value", "host", "type"}
HOSTS = {"currentHost"}
TYPES = {"dict-add"}


def strip_comments(src):
    """文字列リテラルを保ったまま // コメントを除去する"""
    return re.sub(
        r'"(?:\\.|[^"\\])*"|//[^\n]*',
        lambda m: m.group(0) if m.group(0).startswith('"') else "",
        src,
    )


def to_plist_xml(value):
    """値を defaults write に渡せる XML plist の断片に変換する"""
    if isinstance(value, bool):
        return "<true/>" if value else "<false/>"
    if isinstance(value, int):
        return f"<integer>{value}</integer>"
    if isinstance(value, float):
        return f"<real>{value!r}</real>"
    if isinstance(value, str):
        return f"<string>{escape(value)}</string>"
    if isinstance(value, list):
        return "<array>" + "".join(to_plist_xml(v) for v in value) + "</array>"
    if isinstance(value, dict):
        return "<dict>" + "".join(
            f"<key>{escape(str(k))}</key>{to_plist_xml(v)}" for k, v in value.items()
        ) + "</dict>"
    raise ValueError(f"unsupported value: {value!r}")


def value_args(value):
    """値から defaults write の型指定と値の引数を作る"""
    if isinstance(value, bool):
        return ["-bool", "true" if value else "false"]
    if isinstance(value, int):
        return ["-int", str(value)]
    if isinstance(value, float):
        return ["-float", repr(value)]
    if isinstance(value, str):
        return ["-string", value]
    # array や dict は型を保つため XML plist で渡す
    return [to_plist_xml(value)]


def normalize(raw):
    """設定値を {value, host, type} の形に揃える"""
    if isinstance(raw, list):
        raise ValueError("array must be wrapped in {\"value\": ...}")
    if not isinstance(raw, dict):
        return {"value": raw}
    unknown = set(raw) - WRAPPER_FIELDS
    if unknown:
        raise ValueError(f"unknown fields: {sorted(unknown)}")
    if "value" not in raw:
        raise ValueError("missing \"value\"")
    if "host" in raw and raw["host"] not in HOSTS:
        raise ValueError(f"unknown host: {raw['host']!r}")
    if "type" in raw and raw["type"] not in TYPES:
        raise ValueError(f"unknown type: {raw['type']!r}")
    return raw


def build_command(domain, key, setting):
    cmd = ["defaults"]
    if setting.get("host") == "currentHost":
        cmd.append("-currentHost")
    cmd += ["write", domain, key]

    value = setting["value"]
    if setting.get("type") == "dict-add":
        if not isinstance(value, list):
            raise ValueError("dict-add value must be an array of {\"key\", \"value\"}")
        cmd.append("-dict-add")
        for item in value:
            if not isinstance(item, dict) or set(item) != {"key", "value"}:
                raise ValueError(f"invalid dict-add item: {item!r}")
            cmd += [str(item["key"]), to_plist_xml(item["value"])]
    else:
        cmd += value_args(value)

    return " ".join(shlex.quote(arg) for arg in cmd)


def build(config):
    if not isinstance(config, dict):
        raise ValueError("top level must be an object")
    lines = ["#!/bin/bash -eu", "", "# This file is generated by build.py. Do not edit.", ""]
    for domain, settings in config.items():
        if not isinstance(settings, dict):
            raise ValueError(f"{domain}: must be an object")
        for key, raw in settings.items():
            try:
                lines.append(build_command(domain, key, normalize(raw)))
            except ValueError as e:
                raise ValueError(f"{domain} > {key}: {e}") from None
    return "\n".join(lines) + "\n"


def main():
    try:
        config = json.loads(strip_comments(sys.stdin.read()))
        sys.stdout.write(build(config))
    except ValueError as e:
        sys.exit(f"error: {e}")


if __name__ == "__main__":
    main()
